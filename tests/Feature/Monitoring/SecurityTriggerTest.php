<?php

namespace Tests\Feature\Monitoring;

use App\Models\AutomationEvent;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Tests\Concerns\BuildsTenants;
use Tests\TestCase;

/**
 * `monitoring.security_needs_attention` — the automation trigger behind "tell
 * somebody when a machine's defences go bad".
 *
 * ── What these tests are really guarding ──────────────────────────
 *
 * The feature is not "can it fire". It is "does it fire ONCE". A device beats
 * every 60 seconds, so a trigger that fired whenever the antivirus was off
 * would send an email a minute for as long as it stayed off — which does not
 * alert anybody, it teaches them to filter the alerts. So the test that
 * matters most here is the one asserting a SECOND beat raises nothing, and
 * every other test exists to stop that one passing for the wrong reason: a
 * trigger that never fires at all would sail through it.
 */
class SecurityTriggerTest extends TestCase
{
    use BuildsTenants, RefreshDatabase;

    private const KEY = 'monitoring.security_needs_attention';

    private function beat($user, ?array $security = null, bool $withSpecs = true)
    {
        $specs = ['ram_gb' => 31];

        if ($security !== null) {
            $specs['security'] = $security;
        }

        return $this->signedInAs($user)->postJson('/api/v1/monitoring/heartbeat', [
            'device_key'   => 'dk-security',
            'platform'     => 'windows',
            'capabilities' => $withSpecs ? ['activity', 'specs'] : ['activity'],
            'specs'        => $specs,
        ]);
    }

    private function raised(): int
    {
        return AutomationEvent::withoutGlobalScopes()->where('event_key', self::KEY)->count();
    }

    public function test_a_machine_whose_defences_go_bad_raises_the_trigger_once(): void
    {
        $alpha = $this->provisionTenant('Alpha');

        $this->beat($alpha['admin'], ['antivirus' => 'good', 'firewall' => 'good'])
            ->assertNoContent();
        $this->assertSame(0, $this->raised(), 'A healthy machine raises nothing.');

        $this->beat($alpha['admin'], ['antivirus' => 'poor', 'firewall' => 'good'])
            ->assertNoContent();
        $this->assertSame(1, $this->raised(), 'Going bad is the event.');

        // THE ONE THAT MATTERS. Same fault, still there, reported again 60
        // seconds later. An automation that emails on this would send one a
        // minute until somebody fixed the machine.
        $this->beat($alpha['admin'], ['antivirus' => 'poor', 'firewall' => 'good'])
            ->assertNoContent();
        $this->beat($alpha['admin'], ['antivirus' => 'poor', 'firewall' => 'good'])
            ->assertNoContent();
        $this->assertSame(1, $this->raised(),
            'Still broken is not news. The trigger is the transition, not the state.');
    }

    public function test_a_fault_that_is_fixed_and_comes_back_is_news_again(): void
    {
        // The control for the test above. Without it, a trigger that fired
        // exactly once per device for ever would pass every assertion there —
        // and would then stay silent the second time somebody switched their
        // antivirus off, which is the failure nobody would notice until it
        // mattered.
        $alpha = $this->provisionTenant('Alpha');

        $this->beat($alpha['admin'], ['antivirus' => 'good']);
        $this->beat($alpha['admin'], ['antivirus' => 'poor']);
        $this->assertSame(1, $this->raised());

        $this->beat($alpha['admin'], ['antivirus' => 'good']);
        $this->assertSame(1, $this->raised(), 'Recovering is not itself an alert.');

        $this->beat($alpha['admin'], ['antivirus' => 'poor']);
        $this->assertSame(2, $this->raised(), 'A second fault is a second alert.');
    }

    public function test_a_beat_that_reports_no_security_is_not_a_recovery(): void
    {
        // An older agent, a browser session, or a Windows Server with no
        // Security Center all report nothing. Reading that as "fixed" would
        // re-arm the trigger, so the next real report would fire a SECOND
        // time for a fault nobody touched — an alert generated by the
        // monitoring rather than by the machine.
        $alpha = $this->provisionTenant('Alpha');

        $this->beat($alpha['admin'], ['antivirus' => 'poor']);
        $this->assertSame(1, $this->raised());

        // Beats carrying specs but no security block at all.
        $this->beat($alpha['admin'], null);
        $this->beat($alpha['admin'], null);
        $this->assertSame(1, $this->raised(), 'Silence is not a report of health.');

        $this->beat($alpha['admin'], ['antivirus' => 'poor']);
        $this->assertSame(1, $this->raised(),
            'The same unfixed fault must not re-fire because a beat in between said nothing.');
    }

    public function test_not_monitored_is_a_fact_about_windows_not_an_alarm(): void
    {
        // Normal under domain policy. Raising it would fire across a whole
        // office at once, and then the machine that matters arrives looking
        // like the forty-one that do not.
        $alpha = $this->provisionTenant('Alpha');

        $this->beat($alpha['admin'], [
            'antivirus' => 'not_monitored',
            'firewall'  => 'not_monitored',
            'updates'   => 'not_monitored',
        ]);
        $this->assertSame(0, $this->raised());

        // Control: this device CAN raise the trigger, so the zero above is the
        // rule rather than a fixture that was never capable of firing.
        $this->beat($alpha['admin'], ['antivirus' => 'poor']);
        $this->assertSame(1, $this->raised());
    }

    public function test_the_event_names_each_area_so_an_automation_can_filter_on_one(): void
    {
        // The condition field picker offers the fields an event actually
        // carries, so an area missing from the payload is a filter nobody can
        // build — "email me only when the FIREWALL is off" has to be possible
        // without parsing a sentence.
        $alpha = $this->provisionTenant('Alpha');

        $this->beat($alpha['admin'], [
            'antivirus' => 'good',
            'firewall'  => 'poor',
            'updates'   => 'snoozed',
        ]);

        $event = AutomationEvent::withoutGlobalScopes()->where('event_key', self::KEY)->sole();
        $payload = $event->payload ?? [];

        $this->assertSame('poor', $payload['firewall'] ?? null);
        $this->assertSame('snoozed', $payload['updates'] ?? null);
        $this->assertSame('ok', $payload['antivirus'] ?? null,
            'A healthy area says so, rather than being absent — an absent key '
            .'cannot be filtered on and reads as "no answer".');
        $this->assertSame('firewall, updates', $payload['areas'] ?? null);
    }
}
