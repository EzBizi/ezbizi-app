/*
 * The Windows softphone, as far as JavaScript is concerned.
 *
 * Flutter cannot reach the Twilio Voice SDK on Windows — the SDK is a browser
 * script and there is no Windows build — so the desktop app hosts this page in
 * WebView2 and the two halves talk over postMessage.
 *
 * ── The protocol, deliberately small ────────────────────────────────
 *
 * Dart -> JS, arriving on `chrome.webview`'s message event. webview_windows
 * sends with PostWebMessageAsJson, so `event.data` is a parsed OBJECT - it
 * said AsString here for days while the listener was on the wrong object, and
 * both halves of that sentence were wrong in the same direction:
 *
 *   {type:'setup',   token}     register with Twilio
 *   {type:'connect', to, callerId}
 *   {type:'hangup'}
 *   {type:'digits',  digits}   keys pressed on the live call (DTMF)
 *   {type:'accept'}             answer the ringing call
 *   {type:'decline'}
 *
 * JS -> Dart, each `window.chrome.webview.postMessage(json)`:
 *
 *   {type:'ready',      registered:bool}
 *   {type:'incoming',   from}
 *   {type:'accepted'}   |  {type:'ended'}  |  {type:'error', message}
 *
 * It stays this small on purpose: every message is a thing the Dart side's
 * VoiceDevice interface already has a name for, so neither half has to model
 * the other's state machine. The SDK's own Call object never crosses.
 */
(function () {
  'use strict';

  var statusEl = document.getElementById('status');

  /**
   * Ringtone and DTMF overrides.
   *
   * The SDK's default is a Twilio CDN this page's `media-src 'self'` blocks,
   * so with the defaults the phone registers and routes calls perfectly and
   * rings SILENTLY. The sounds are vendored beside this file instead.
   *
   * Keys are `Device.SoundName` values. An explicit URL bypasses the SDK's own
   * extension negotiation, so .mp3 is right everywhere — WebView2 is Chromium.
   */
  var SOUNDS = {
    incoming: 'sounds/incoming.mp3',
    outgoing: 'sounds/outgoing.mp3',
    disconnect: 'sounds/disconnect.mp3',
    dtmf0: 'sounds/dtmf-0.mp3',
    dtmf1: 'sounds/dtmf-1.mp3',
    dtmf2: 'sounds/dtmf-2.mp3',
    dtmf3: 'sounds/dtmf-3.mp3',
    dtmf4: 'sounds/dtmf-4.mp3',
    dtmf5: 'sounds/dtmf-5.mp3',
    dtmf6: 'sounds/dtmf-6.mp3',
    dtmf7: 'sounds/dtmf-7.mp3',
    dtmf8: 'sounds/dtmf-8.mp3',
    dtmf9: 'sounds/dtmf-9.mp3',
    dtmfh: 'sounds/dtmf-hash.mp3',
    dtmfs: 'sounds/dtmf-star.mp3'
  };

  var device = null;
  var activeCall = null;
  var pendingCall = null;

  function send(payload) {
    try {
      window.chrome.webview.postMessage(JSON.stringify(payload));
    } catch (e) {
      // Nothing to do: the only transport back is the one that just failed.
    }
  }

  function note(text) {
    if (statusEl) statusEl.textContent = text;
  }

  // `code` is Twilio's, when there is one: 31402 is a microphone that could
  // not be opened, which Dart turns into a sentence somebody can act on.
  function fail(message, code) {
    note('error: ' + message);
    send({ type: 'error', message: String(message), code: code || null });
  }

  /** Both call objects go through here so no listener is registered twice. */
  function watch(call) {
    call.on('accept', function () {
      activeCall = call;
      pendingCall = null;
      note('on a call');
      send({ type: 'accepted' });
    });

    // disconnect, cancel and reject all end up in the same place on the Dart
    // side — there is no call any more — and collapsing them here keeps the
    // protocol from carrying three words for one fact.
    ['disconnect', 'cancel', 'reject'].forEach(function (event) {
      call.on(event, function () {
        if (activeCall === call) activeCall = null;
        if (pendingCall === call) pendingCall = null;
        note('idle');
        send({ type: 'ended' });
      });
    });

    call.on('error', function (error) {
      fail(error && error.message ? error.message : 'call failed', error && error.code);
    });
  }

  /**
   * Turn off the SDK's own incoming ring, if this build of it has one.
   *
   * Guarded rather than assumed: `device.audio` is null when the browser hands
   * the SDK no audio helper, and an unguarded call here would throw inside
   * setup() and take registration down with it — trading two ringtones for a
   * phone that does not ring at all.
   */
  function silenceOwnRing(d) {
    try {
      if (d && d.audio && typeof d.audio.incoming === 'function') {
        d.audio.incoming(false);
      }

      // And the outgoing tone, for the same reason at the other end of the
      // call: outbound ringback is <Dial ringTone>, generated by Twilio on
      // the server, so the vendored outgoing.mp3 is a second ring on top of
      // the real one. The file stays in SOUNDS because the SDK still wants a
      // URL it can resolve; this is what stops it being played.
      if (d && d.audio && typeof d.audio.outgoing === 'function') {
        d.audio.outgoing(false);
      }
    } catch (e) {
      // An older SDK without the toggle. Two tones is worse than one and
      // better than a desk that cannot take a call.
    }
  }

  function setup(token) {
    try {
      if (device) device.destroy();

      device = new window.Twilio.Device(token, {
        sounds: SOUNDS,

        // Chromium in WebView2 supports Opus; naming it stops the SDK
        // negotiating something worse on a slow line.
        codecPreferences: ['opus', 'pcmu']
      });

      // ── ONE RINGTONE, AND IT IS OURS ─────────────────────────
      //
      // The SDK rings for an incoming call and EzBizi rings too — see
      // CallAlerts, which every platform uses — so the desktop played both
      // at once. Jose: "it was ringing twice, with the new ring that u put
      // for fixing web, and the old ringing from ezbizi desktop app."
      //
      // The web build already turned the SDK's incoming ring off for exactly
      // this reason and the desktop was never given the same treatment. It
      // was audible before as two similar tones overlapping; making ours a
      // distinct double burst is what turned an unnoticed overlap into an
      // obvious one.
      //
      // Ours survives, for the reason the web comment gives: it is the same
      // alert on Windows, Android, iOS and the browser, and a desktop that
      // rings differently from the phone in your pocket is a desk people
      // learn to distrust.
      //
      // ONLY `incoming`. `outgoing`, `disconnect` and the DTMF keys stay:
      // nothing else here duplicates them, and the outbound ringback in
      // particular is carried by <Dial ringTone> rather than by CallAlerts,
      // so silencing it would leave a caller listening to nothing.
      silenceOwnRing(device);

      device.on('incoming', function (call) {
        pendingCall = call;
        watch(call);
        note('ringing');
        send({
          type: 'incoming',
          from: (call.parameters && call.parameters.From) || ''
        });
      });

      device.on('error', function (error) {
        fail(error && error.message ? error.message : 'device error');
      });

      device.on('tokenWillExpire', function () {
        // Dart owns the token lifecycle; it refetches and sends setup again.
        send({ type: 'tokenExpiring' });
      });

      device.register().then(
        function () {
          note('registered');
          send({ type: 'ready', registered: true });
        },
        function (error) {
          // Registered false rather than an error: the desk has a state for
          // "cannot take a call" and it is not the same as a failure.
          note('not registered');
          send({
            type: 'ready',
            registered: false,
            message: error && error.message ? error.message : ''
          });
        }
      );
    } catch (e) {
      fail(e && e.message ? e.message : 'could not start the phone');
      send({ type: 'ready', registered: false });
    }
  }

  function connect(to, callerId) {
    if (!device) return fail('the phone is not started');

    var params = { To: to, EzBiziDirection: 'outbound' };
    if (callerId) params.CallerId = callerId;

    device.connect({ params: params }).then(
      function (call) {
        watch(call);
        activeCall = call;
        note('calling');
      },
      function (error) {
        fail(error && error.message ? error.message : 'the call was refused', error && error.code);
      }
    );
  }

  /*
   * HOST MESSAGES ARRIVE ON `chrome.webview`, NOT ON `window`.
   *
   * This listened on `window` and so never heard the host at all. The page
   * loaded, said so, and then sat there: the token was posted in and landed
   * nowhere, `device.register()` was never called, no 'ready' ever went back,
   * and Dart's 10-second wait expired on `registered: false` with no reason to
   * report - which is the generic "the network is blocking the connection"
   * banner that desktop showed on every launch for days. The page looked
   * perfect. Nothing was wrong with the network, the token, or Twilio.
   *
   * `window.addEventListener('message')` is the right call in a BROWSER, for
   * postMessage between frames. WebView2 host messages are a different channel
   * and this is the one A-1 Tools uses, where the phone works.
   *
   * And `event.data` is already an OBJECT: webview_windows sends with
   * PostWebMessageAsJson (webview.cc:714), so WebView2 parses it before we see
   * it. `JSON.parse` on it throws, which the old catch swallowed - so fixing
   * only the listener would have left the same silence.
   */
  function onHostMessage(raw) {
    var message;
    try {
      message = typeof raw === 'string' ? JSON.parse(raw) : raw;
    } catch (e) {
      // Said out loud rather than dropped. A message the host sent and this
      // page could not read is how the whole thing went quiet last time.
      return fail('unreadable message from the app');
    }
    if (!message || !message.type) return;

    switch (message.type) {
      case 'setup':
        return setup(message.token);
      case 'connect':
        return connect(message.to, message.callerId);
      case 'digits':
        if (activeCall) activeCall.sendDigits(String(message.digits));
        return;
      case 'hangup':
        if (activeCall) activeCall.disconnect();
        if (device) device.disconnectAll();
        return;
      case 'accept':
        if (pendingCall) pendingCall.accept();
        return;
      case 'decline':
        if (pendingCall) pendingCall.reject();
        return;
    }
  }

  try {
    window.chrome.webview.addEventListener('message', function (event) {
      onHostMessage(event.data);
    });
  } catch (e) {
    // Opened directly in a browser rather than hosted by the app. The page
    // still loads so a developer can exercise getUserMedia by hand; no host
    // message will ever arrive, which is the honest state and not this bug.
  }

  // Posted LAST, after the listener is attached: Dart gates the token on it,
  // and a token that arrives before there is anything listening is dropped
  // with no retry.
  note('waiting for a token');
  send({ type: 'loaded' });
})();
